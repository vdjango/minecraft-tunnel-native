#!/usr/bin/env python3
"""Embed the audited JSON protocol tables in a portable C++ header.

MSVC rejects one string literal longer than 16,380 single-byte characters.
The generated header therefore uses adjacent literals of at most 8 KiB.  The
result is still a compile-time char array, so the runtime does not open a data
file or allocate while loading the protocol tables.
"""

from __future__ import annotations

import argparse
from pathlib import Path


MAX_LITERAL_SOURCE_BYTES = 8192


def _byte_token(byte: int) -> str:
    if byte == 0x0A:
        return r"\n"
    if byte == 0x0D:
        return r"\r"
    if byte == 0x09:
        return r"\t"
    if byte == 0x5C:
        return r"\\"
    if byte == 0x22:
        return r'\"'
    if 0x20 <= byte <= 0x7E:
        return chr(byte)
    # Three octal digits cannot consume following ASCII hex digits (unlike \x).
    return f"\\{byte:03o}"


def adjacent_literals(data: bytes) -> list[str]:
    """Return quoted C++ literals whose source representation is bounded."""
    chunks: list[str] = []
    current: list[str] = []
    source_size = 2  # opening and closing quotes
    for byte in data:
        token = _byte_token(byte)
        if current and source_size + len(token) > MAX_LITERAL_SOURCE_BYTES:
            chunks.append('"' + ''.join(current) + '"')
            current = []
            source_size = 2
        current.append(token)
        source_size += len(token)
    if current or not chunks:
        chunks.append('"' + ''.join(current) + '"')
    return chunks


def render_member(name: str, data: bytes) -> str:
    lines = [f"inline constexpr char {name}[] ="]
    lines.extend(f"    {literal}" for literal in adjacent_literals(data))
    lines[-1] += ";"
    return "\n".join(lines)


def render_header(chat: bytes, legacy: bytes) -> str:
    return (
        "// Generated from the audited Minecraft packet ID tables. See THIRD_PARTY_NOTICES.md.\n"
        "// Do not edit this file; it is regenerated during CMake configure.\n"
        "#pragma once\n"
        "namespace bridge::game {\n"
        f"{render_member('profiles_json', chat)}\n"
        f"{render_member('legacy_json', legacy)}\n"
        "}\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--chat", type=Path, required=True)
    parser.add_argument("--legacy", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(
        render_header(args.chat.read_bytes(), args.legacy.read_bytes()),
        encoding="utf-8",
        newline="\n",
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
